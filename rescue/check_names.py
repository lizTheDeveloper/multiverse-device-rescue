def check_name(module_name: str) -> str:
    """The check's name for people; a module missing from the table gets its
    id in words ("new_check" -> "New check"), never the raw id."""
    name = CHECK_NAMES.get(module_name)
    if name:
        return name
    words = str(module_name or "").replace("_", " ").strip()
    return words[:1].upper() + words[1:] if words else "A check"


# Error text -> kind. Checked in order; the first that matches wins.
_PERMISSION_MARKERS = (
    "operation not permitted", "permission denied", "errno 1]", "errno 13]",
    "full disk access", "not authorized", "access is denied", "requires admin",
    "requires root", "must be run as root", "tcc",
)


def error_kind(error: str | None, supported: bool = True, complete: bool = True) -> str | None:
    """What kind of "couldn't check" a module entry is, or None when it ran.

    ``timeout``     it took too long and was stopped
    ``permission``  the system refused it (often Full Disk Access)
    ``skipped``     it never started (the scan's time budget ran out)
    ``unsupported`` it can't run on this computer
    ``error``       anything else went wrong
    ``unfinished``  it ran but stopped before the end
    """
    if error:
        text = str(error).lower()
        if "timed out" in text or "took too long" in text:
            return "timeout"
        if text.startswith("skipped"):
            return "skipped"
        if any(m in text for m in _PERMISSION_MARKERS):
            return "permission"
        return "error"
    if not supported:
        return "unsupported"
    if not complete:
        return "unfinished"
    return None
