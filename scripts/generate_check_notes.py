#!/usr/bin/env python3
"""Generate ``desktop/renderer/game/check-notes.js`` for the sweep screen.

While a scan runs, the desktop app's sweep shows the check running right now:
what it looks at, why, and where on the computer. Those lines are written by
hand, one per check, in ``scripts/check_notes.json`` (``what`` / ``why`` /
``where``), from reading each module's ``check()``. This script joins them with
the live registry (:func:`rescue.registry.discover_modules`, the same discovery
the CLI and ``docs/modules.md`` use) for each check's category and platforms,
and writes a plain ES module the renderer imports.

It fails when a shipped module has no note, when a note names a module that
no longer ships, or when a line breaks the length and wording rules, so a new
check can't reach the sweep unexplained.

Usage::

    python scripts/generate_check_notes.py           # write the JS file
    python scripts/generate_check_notes.py --check   # exit 1 if stale or incomplete

Discovery imports every module's ``__init__.py`` (it never calls ``check()``).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from rescue.models import Platform  # noqa: E402
from rescue.registry import discover_modules  # noqa: E402

MODULES_DIR = REPO_ROOT / "modules"
SOURCE_PATH = REPO_ROOT / "scripts" / "check_notes.json"
OUTPUT_PATH = REPO_ROOT / "desktop" / "renderer" / "game" / "check-notes.js"

LIMITS = {"what": 60, "why": 110, "where": 90}
PLATFORM_LABELS = {Platform.DARWIN: "macOS", Platform.WIN32: "Windows", Platform.LINUX: "Linux"}
# The same rules the lessons and the sweep follow: no durations, no verdicts.
TIME_WORDS = re.compile(r"\b(seconds?|minutes?|hours?|days?|weeks?)\b", re.I)
VERDICTS = re.compile(r"your (computer|mac|pc) (has|is)|you(’|')?ve been hacked|you are infected", re.I)

HEADER = """// GENERATED by scripts/generate_check_notes.py from scripts/check_notes.json
// and the module registry. Do not edit by hand: edit the JSON and re-run it.
// For each check: what it looks at, why, and where on the computer (shown on
// the sweep while it runs), its category and the platforms it runs on.
"""


def problems_in(name: str, note: object) -> list[str]:
    if not isinstance(note, dict):
        return [f"{name}: not an object"]
    bad = []
    for key, limit in LIMITS.items():
        text = note.get(key)
        if not isinstance(text, str) or not text.strip():
            bad.append(f"{name}: no {key}")
            continue
        if len(text) > limit:
            bad.append(f"{name}: {key} is {len(text)} characters (at most {limit})")
        if TIME_WORDS.search(text):
            bad.append(f"{name}: time word in {key}")
        if VERDICTS.search(text):
            bad.append(f"{name}: says what is wrong with the computer in {key}")
    return bad


def build() -> tuple[str, list[str]]:
    modules = discover_modules(MODULES_DIR)
    notes = json.loads(SOURCE_PATH.read_text(encoding="utf-8"))
    names = {m.name for m in modules}
    errors = [f"{n}: no note in scripts/check_notes.json" for n in sorted(names - notes.keys())]
    errors += [f"{n}: note for a module that doesn't ship" for n in sorted(notes.keys() - names)]
    out = {}
    for m in sorted(modules, key=lambda m: m.name):
        note = notes.get(m.name)
        if note is None:
            continue
        errors += problems_in(m.name, note)
        out[m.name] = {
            "what": note.get("what", ""),
            "why": note.get("why", ""),
            "where": note.get("where", ""),
            "category": m.category,
            "platforms": [PLATFORM_LABELS[p] for p in PLATFORM_LABELS if p in m.platforms],
        }
    body = json.dumps(out, indent=1, ensure_ascii=False, sort_keys=True)
    return f"{HEADER}export const CHECK_NOTES = {body};\nexport default CHECK_NOTES;\n", errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the JS file is stale or a note is missing")
    args = parser.parse_args()
    text, errors = build()
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if args.check:
        current = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else ""
        if current != text:
            print(f"{OUTPUT_PATH.relative_to(REPO_ROOT)} is stale: run scripts/generate_check_notes.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT_PATH.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
